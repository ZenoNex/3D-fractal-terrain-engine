// 3-D Classic Perlin (CPU side – used only for seed preview or debugging)
inline float perlin(float x, float y, float z) {
    int X = int(std::floor(x)) & 255;
    int Y = int(std::floor(y)) & 255;
    int Z = int(std::floor(z)) & 255;

    x -= std::floor(x);
    y -= std::floor(y);
    z -= std::floor(z);

    float u = x*x*(3.0f-2.0f*x);
    float v = y*y*(3.0f-2.0f*y);
    float w = z*z*(3.0f-2.0f*z);

    auto inc = [](int n) { return perlinPermutation[n & 255]; };

    int aaa = inc(inc(inc(X)+Y)+Z);
    int aba = inc(inc(inc(X)+Y+1)+Z);
    int aab = inc(inc(inc(X)+Y)+Z+1);
    int abb = inc(inc(inc(X)+Y+1)+Z+1);
    int baa = inc(inc(inc(X+1)+Y)+Z);
    int bba = inc(inc(inc(X+1)+Y+1)+Z);
    int bab = inc(inc(inc(X+1)+Y)+Z+1);
    int bbb = inc(inc(inc(X+1)+Y+1)+Z+1);

    auto grad = [](int hash, float x, float y, float z) {
        int h = hash & 15;
        float u = h < 8 ? x : y;
        float v = h < 4 ? y : (h == 12 || h == 14 ? x : z);
        return ((h & 1) == 0 ? u : -u) + ((h & 2) == 0 ? v : -v);
    };

    float x1 = glm::mix(grad(aaa, x, y, z), grad(baa, x-1, y, z), u);
    float x2 = glm::mix(grad(aba, x, y-1, z), grad(bba, x-1, y-1, z), u);
    float y1 = glm::mix(x1, x2, v);

    float x3 = glm::mix(grad(aab, x, y, z-1), grad(bab, x-1, y, z-1), u);
    float x4 = glm::mix(grad(abb, x, y-1, z-1), grad(bbb, x-1, y-1, z-1), u);
    float y2 = glm::mix(x3, x4, v);

    return (glm::mix(y1, y2, w) + 1.0f) * 0.5f; // [-1,1] → [0,1]
}
